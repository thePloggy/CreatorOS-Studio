type Tr = (s: string) => string

/** Messages with variables: French pattern → English. `tr` translates a fragment
 *  (nested message, hint after "—"). The first matching pattern wins. */
export const MOTIFS_SERVEUR: [RegExp, (m: RegExpMatchArray, tr: Tr) => string][] = [
  [/^« (.+) » existe déjà$/, m => `“${m[1]}” already exists`],
  [/^« (.+) » absent du dossier input\/$/, m => `“${m[1]}” not found in the input/ folder`],
  [/^job « (.+) » : encore en cours$/, m => `job “${m[1]}”: still running`],
  [/^job « (.+) » : ni annulable ni supprimable$/, m => `job “${m[1]}”: can be neither cancelled nor deleted`],
  [/^recadrage impossible : ([\s\S]+)$/, (m, tr) => `crop failed: ${tr(m[1])}`],
  [/^reprise échouée : ([\s\S]+)$/, (m, tr) => `resume failed: ${tr(m[1])}`],
  [/^une tâche est déjà en cours \((.+)\)$/, m => `a task is already running (${m[1]})`],
  [/^T0 : terme bloqué « (.+) »( dans le prompt| — apparu dans un tirage wildcard)$/,
    m => `T0: blocked term “${m[1]}”${m[2] === ' dans le prompt' ? ' in the prompt' : ' — it came from a wildcard draw'}`],
  [/^délai dépassé \((\d+) s\) sans résultat$/, m => `timed out (${m[1]} s) with no result`],
  [/^délai dépassé \((\d+) s\) côté Comfy$/, m => `timed out (${m[1]} s) on the Comfy side`],
  [/^déjà fluide : (\d+) i\/s$/, m => `already smooth: ${m[1]} fps`],
  [/^finition « (.+) » inconnue$/, m => `unknown finishing “${m[1]}”`],
  [/^durée (\d+) s hors capacité de ce moteur \(maximum (\d+) s en VRAM à sa résolution\) — réduire la durée ou changer de moteur$/,
    m => `duration ${m[1]} s is beyond this engine’s capacity (max ${m[2]} s in VRAM at its resolution) — shorten it or switch engines`],
  [/^clip trop long pour la retouche \(([\d.]+) s\) : 10 s au plus — retoucher plan par plan$/,
    m => `clip too long for editing (${m[1]} s): 10 s max — edit it shot by shot`],
  [/^aucun plan produit — sortie modèle : « ([\s\S]*) »$/, m => `no shot produced — model output: “${m[1]}”`],
  [/^aucune scène produite — sortie modèle : « ([\s\S]*) »$/, m => `no scene produced — model output: “${m[1]}”`],
  [/^délai dépassé \(([\d.]+) s\) sur (.+) — le CPU est lent, réessayer ou choisir un modèle plus léger$/,
    m => `timed out (${m[1]} s) on ${m[2]} — the CPU is slow, try again or pick a lighter model`],
  [/^Ollama injoignable sur (\S+) : ([\s\S]+)$/, m => `Ollama unreachable at ${m[1]}: ${m[2]}`],
  [/^Ollama a répondu (\d+) pour (.+)$/, m => `Ollama returned ${m[1]} for ${m[2]}`],
  // erreurs.js — ComfyUI failures
  [/^rendu interrompu au nœud (\S+) \(([^)]*)\) — annulé, ou coupé par un autre rendu lancé par-dessus$/,
    m => `render interrupted at node ${m[1]} (${m[2]}) — cancelled, or cut off by another render started on top`],
  [/^exécution non terminée \((.*)\)$/, (m, tr) => `execution not finished (${tr(m[1])})`],
  [/^refus de ComfyUI : ([\s\S]+)$/, m => `rejected by ComfyUI: ${m[1]}`],
  [/^recette refusée par ComfyUI — ([\s\S]+)$/,
    (m, tr) => `recipe rejected by ComfyUI — ${m[1].split(' — ').map(p => p.split(' ; ').map(tr).join(' ; ')).join(' — ')}`],
  [/^nœud (\S+) \(([^)]*)\)((?:\.\w+)?) : ([\s\S]+)$/, (m, tr) => {
    /* "node N (type): cause — hint": the cause is ComfyUI's raw text
       (already English); only the hint is translated. */
    const [cause, ...conseil] = m[4].split(' — ')
    const c = cause.replace(/\(reçu : /g, '(received: ').replace(/ ; … \((\d+) de plus\)$/, ' ; … ($1 more)')
    return `node ${m[1]} (${m[2]})${m[3]}: ${[c, ...conseil.map(tr)].join(' — ')}`
}],
]
